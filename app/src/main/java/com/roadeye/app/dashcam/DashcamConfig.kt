package com.roadeye.app.dashcam

/**
 * Константы видеорегистратора (Вариант C: отдельный видео-Surface,
 * независимый от YOLO-детекции). Все числовые значения — рабочие
 * дефолты (DECISION, принятые Claude без подтверждения пользователем
 * там, где это явно отмечено), НЕ откалиброваны на реальном устройстве.
 * Пересмотреть по аналогии с CameraConfig.FIXED_FOCUS_DISTANCE — через
 * эмпирический тест, не молча.
 */
object DashcamConfig {

    // --- Видео-поток ---
    // ИСТОЧНИК (что реально запрашивается у камеры через SurfaceTexture) —
    // ВСЕГДА 1280x720, 16:9, НЕ меняется. Подтверждено рабочим на этом
    // устройстве (реальные записи, стабильная комбинация с ImageReader
    // 640x480 под детекцию). Менять эти два числа — значит заново
    // рисковать комбинацией потоков камеры (см. INFO_SUPPORTED_HARDWARE_LEVEL),
    // а это никогда не тестировалось на других значениях.
    const val VIDEO_WIDTH = 1280
    const val VIDEO_HEIGHT = 720

    // ВЫХОД (реальный размер кадра энкодера/итогового файла) — 5:3 по
    // запросу пользователя (соотношение сторон экрана планшета), ОТДЕЛЬНО
    // от источника выше. Несовпадение источник/выход не проблема — тот же
    // CENTER_CROP-расчёт, что уже используется для поворотов
    // (DashcamGlCompositor.computeRotatedCropPositions), сам обрежет
    // разницу в пропорциях: 16:9 источник немного шире 5:3 выхода,
    // обрежутся только узкие поля по бокам. Альбомные размеры — камера НЕ
    // пересоздаётся, энкодер стартует сразу с ними; книжные (720 -> 1200) —
    // при смене ориентации, см. DashcamController.handleOrientationSwitch().
    const val VIDEO_OUTPUT_WIDTH_LANDSCAPE = 1200
    const val VIDEO_OUTPUT_HEIGHT_LANDSCAPE = 720

    const val VIDEO_BITRATE_BPS = 8_000_000 // было 4 Mbps, поднято по запросу пользователя
    const val VIDEO_FRAME_RATE = 30
    // Должен быть <= (PRE_ROLL_MS / 1000), иначе pre-roll окно может
    // остаться без опорного (key) кадра для декодирования.
    const val KEYFRAME_INTERVAL_SEC = 1

    // --- Кольцевой буфер в RAM ---
    const val PRE_ROLL_MS = 15_000L

    // --- Событие (удар / двойной тап) — фиксированная длительность клипа ---
    // 15 сек pre-roll + 45 сек после события = 60 сек итоговый клип,
    // как описано в задаче.
    const val POST_EVENT_MS = 45_000L
    const val SHOCK_THRESHOLD_G = 2.5f // было 2.0, поднято по запросу пользователя — HYPOTHESIS, не проверено реальным ударом
    const val SHOCK_DEBOUNCE_MS = 5_000L // не триггерить повторно чаще раза в 5 сек

    // --- Циклическая запись от кнопки (NORMAL, не FAVORITE) ---
    // Независима от длины событийного клипа выше — пользователь явно
    // запросил 5 минут на сегмент для кнопки.
    const val CONTINUOUS_SEGMENT_MS = 5 * 60 * 1000L

    // --- Хранилище на SD ---
    // Было 5GB при битрейте 4 Mbps. Битрейт удвоен (см. VIDEO_BITRATE_BPS) —
    // при той же квоте глубина истории циклической записи упала бы вдвое,
    // поэтому RESERVED_ZONE_BYTES тоже удвоен (5GB -> 8GB), а
    // FAVORITES_QUOTA_BYTES остался прежним (2GB) — вся добавка ушла под
    // normal (NORMAL_QUOTA_BYTES = RESERVED - FAVORITES, см. ниже). Это и
    // есть "увеличить размер для циклической записи" по запросу
    // пользователя. При ~1 МБ/с (8 Mbps) 5-минутный сегмент — это ~300 МБ,
    // 6GB под normal — около 20 сегментов, то есть глубина истории
    // осталась примерно той же (~100 мин), что была при 3GB/4 Mbps.
    const val RESERVED_ZONE_BYTES = 8L * 1024 * 1024 * 1024 // 8GB

    // DEFAULT (НЕ подтверждено пользователем — один из трёх открытых
    // вопросов): фиксированная под-квота под избранное, 2 из 5GB.
    // Внутри неё — вытеснение САМОГО СТАРОГО избранного при переполнении.
    // Если это не тот вариант, который нужен — поменять только эти два
    // значения и логику в DashcamStorageManager.enforceDirQuota().
    const val FAVORITES_QUOTA_BYTES = 2L * 1024 * 1024 * 1024
    const val NORMAL_QUOTA_BYTES = RESERVED_ZONE_BYTES - FAVORITES_QUOTA_BYTES

    // --- Смена ориентации записи (альбомная 1280x720 <-> книжная 720x1280) ---
    // Пересоздание энкодера — дорогая операция (рвёт текущие клипы и сбрасывает
    // pre-roll), поэтому новая ориентация должна продержаться стабильной это
    // время, прежде чем запись реально переключится. Иначе наклон планшета
    // около 45 градусов вызывал бы бесконечные пересоздания.
    const val ORIENTATION_SWITCH_STABLE_MS = 2000L

    // --- Оверлей (вшитый в кадр текст: время/координаты/скорость) ---
    // Позиция — нижний левый угол кадра. Ширина — доля ДЛИННОЙ стороны
    // кадра (одинаковый физический размер в альбомной и книжной), высота
    // считается из пропорций битмапа — иначе текст был бы растянут.
    const val OVERLAY_WIDTH_FRACTION = 0.34f
    const val OVERLAY_UPDATE_INTERVAL_MS = 1000L // текст меняется раз в сек — незачем чаще
    const val OVERLAY_BITMAP_WIDTH = 700
    const val OVERLAY_BITMAP_HEIGHT = 220
    const val OVERLAY_TEXT_SIZE_PX = 34f

    // Остаточная поправка угла ТОЛЬКО для видео, поверх того же
    // totalRotationDegrees, что использует превью. По умолчанию 0 —
    // после перехода на сэмплирование СЫРОГО буфера (без запечённого
    // поворота системной матрицы) видео должно поворачиваться так же, как
    // превью. Если после теста весь кадр окажется повёрнут на кратное 90°,
    // правится ТОЛЬКО это число (90/180/270), больше ничего.
    const val VIDEO_ROTATION_OFFSET_DEGREES = 0

    const val DASHCAM_DIR_NAME = "RoadEyeDashcam"
    const val NORMAL_SUBDIR = "normal"
    const val FAVORITES_SUBDIR = "favorites"
}