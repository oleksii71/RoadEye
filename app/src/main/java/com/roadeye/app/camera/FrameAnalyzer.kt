package com.roadeye.app.camera

/**
 * Точка подключения ML-инференса к потоку кадров с камеры.
 *
 * Принимает уже скопированный NV21-массив байт (не android.media.Image!)
 * — это осознанное архитектурное решение: Image живёт только до close(),
 * что не позволяет передать его асинхронно на другой поток. NV21-копия
 * независима от жизненного цикла кадра камеры, поэтому Camera2Controller
 * может закрыть Image сразу после извлечения байт и передать саму
 * детекцию на ОТДЕЛЬНЫЙ поток — долгий YOLO-инференс тогда никогда не
 * блокирует обработку следующих кадров превью (которое остаётся на
 * потоке чтения кадров с камеры).
 */
fun interface FrameAnalyzer {

    /**
     * @param nv21 кадр в формате NV21, независимая копия байт.
     * @param width ширина кадра в пикселях.
     * @param height высота кадра в пикселях.
     * @param rotationDegrees на сколько градусов повёрнут кадр
     *   относительно естественной ориентации устройства (0/90/180/270) —
     *   нужно, чтобы модель получала кадр в правильной ориентации.
     */
    fun analyze(nv21: ByteArray, width: Int, height: Int, rotationDegrees: Int)
}